"""Write docs/er-diagram.sql: CREATE TABLE statements for the dbt marts, for importing into DrawDB (PostgreSQL syntax).

Columns, types, NOT NULL, primary and foreign keys come from the mart contracts in dbt's manifest, so the diagram
matches what dbt builds. Run `dbt docs generate` (or `dbt parse`) first so the manifest is current, then:

    python scripts/export_marts_ddl.py
"""

import json
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
MANIFEST = REPO / "dbt" / "job_listings" / "target" / "manifest.json"
OUTPUT = REPO / "docs" / "er-diagram.sql"

# Databricks contract types -> PostgreSQL, which DrawDB can import.
TYPES = {"string": "text", "bigint": "bigint", "int": "integer", "double": "double precision",
         "date": "date", "timestamp": "timestamp", "boolean": "boolean"}
# Tables a foreign key points to come first, so every REFERENCES names a table already defined.
ORDER = ("dim_", "fct_", "bridge_", "agg_")
REF = re.compile(r"""ref\(\s*['"](\w+)['"]\s*\)""")


def create_table(node: dict) -> str:
    lines, keys = [], []
    for column in node["columns"].values():
        constraints = column.get("constraints", [])
        not_null = any(c["type"] == "not_null" for c in constraints)
        lines.append(f"  {column['name']} {TYPES[column['data_type']]}{' NOT NULL' if not_null else ''}")
        # Column-level keys apply to that column; model-level ones list their columns.
        keys += [{**c, "columns": [column["name"]]} for c in constraints if c["type"] in ("primary_key", "foreign_key")]
    keys += [c for c in node.get("constraints", []) if c["type"] in ("primary_key", "foreign_key")]

    for key in sorted(keys, key=lambda c: c["type"] != "primary_key"):
        columns = ", ".join(key["columns"])
        if key["type"] == "primary_key":
            lines.append(f"  CONSTRAINT {key['name']} PRIMARY KEY ({columns})")
        else:
            parent = REF.fullmatch(key["to"]).group(1)
            lines.append(f"  CONSTRAINT {key['name']} FOREIGN KEY ({columns}) "
                         f"REFERENCES {parent} ({', '.join(key['to_columns'])})")
    return f"CREATE TABLE {node['name']} (\n" + ",\n".join(lines) + "\n);"


def main() -> None:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    marts = [node for node in manifest["nodes"].values()
             if node["resource_type"] == "model" and node["fqn"][1] == "marts"]
    marts.sort(key=lambda node: (next(i for i, p in enumerate(ORDER) if node["name"].startswith(p)), node["name"]))

    header = "-- Generated by scripts/export_marts_ddl.py from the dbt mart contracts. Don't edit by hand.\n"
    OUTPUT.write_text(header + "\n\n".join(create_table(node) for node in marts) + "\n", encoding="utf-8")
    print(f"Wrote {len(marts)} tables to {OUTPUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
